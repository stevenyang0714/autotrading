// Generates src/generated/glossary.ts from docs/glossary/glossary_seed.yaml (M0.4, D1).
// Only `complete` terms are exported; CompleteTermId is the only type <Metric> accepts, so an
// unknown or unfinished term fails `tsc`. Run with `pnpm gen` (or `make gen` from the repo root).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../../docs/glossary/glossary_seed.yaml");
// Chinese hints (M0.6, ADR-016): presentation only, merged as name_zh / hint_zh.
const zhSource = resolve(here, "../../../docs/glossary/glossary_zh.yaml");
const target = resolve(here, "../src/generated/glossary.ts");

// 02 §22, in order.
const REQUIRED = [
  "term_id",
  "display_name",
  "category",
  "short_definition",
  "full_definition",
  "formula",
  "unit",
  "example",
  "interpretation",
  "why_it_matters",
  "source",
  "source_url",
  "as_of",
  "update_cadence",
  "caveats",
  "related_terms",
  "methodology_version",
];
const FIELDS = [...REQUIRED.slice(0, 8), "direction", ...REQUIRED.slice(8)];

const glossary = parse(readFileSync(source, "utf8"));
const complete = glossary.terms.filter((term) => term.status === "complete");
for (const term of complete) {
  const missing = REQUIRED.filter((field) => {
    const value = term[field];
    return value === undefined || value === null || value === "" || (Array.isArray(value) && !value.length);
  });
  if (missing.length) {
    throw new Error(`${term.term_id} is complete but missing ${missing.join(", ")}`);
  }
}
complete.sort((a, b) => a.term_id.localeCompare(b.term_id));

const zh = parse(readFileSync(zhSource, "utf8")).terms ?? {};
for (const id of Object.keys(zh)) {
  if (!complete.some((term) => term.term_id === id)) {
    throw new Error(`glossary_zh.yaml has ${id}, which is not a complete term`);
  }
}
const entries = Object.fromEntries(
  complete.map((term) => [
    term.term_id,
    {
      ...Object.fromEntries(FIELDS.map((f) => [f, term[f]])),
      ...(zh[term.term_id] ? { name_zh: zh[term.term_id].name, hint_zh: zh[term.term_id].hint } : {}),
    },
  ]),
);
const ids = complete.map((term) => JSON.stringify(term.term_id)).join("\n  | ");

const output = `// GENERATED by scripts/gen-glossary.mjs from docs/glossary/glossary_seed.yaml. Do not edit.
// Regenerate with \`pnpm gen\`; CI fails when this file is out of date.

export const GLOSSARY_VERSION = ${JSON.stringify(String(glossary.version))};

/** Terms with all 17 fields of 02 §22 filled. Only these may be rendered (<Metric>). */
export type CompleteTermId =
  | ${ids};

export interface GlossaryTerm {
  term_id: CompleteTermId;
  display_name: string;
  category: string;
  short_definition: string;
  full_definition: string;
  formula: string;
  unit: string;
  example: string;
  direction: string;
  interpretation: string;
  why_it_matters: string;
  source: string;
  source_url: string;
  as_of: string;
  update_cadence: string;
  caveats: string;
  related_terms: string[];
  methodology_version: string;
  /** Chinese name and one-line hint (docs/glossary/glossary_zh.yaml); presentation only. */
  name_zh?: string;
  hint_zh?: string;
}

export const GLOSSARY: Record<CompleteTermId, GlossaryTerm> = ${JSON.stringify(entries, null, 2)} as Record<CompleteTermId, GlossaryTerm>;
`;
writeFileSync(target, output);
console.log(`glossary.ts: ${complete.length} complete terms`);
