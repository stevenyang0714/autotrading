# ---------- append-only facts ----------


def store(engine: Engine, entity_id: UUID, value: str, **provenance: object) -> FinancialFact:
    with Session(engine, expire_on_commit=False) as session:
        result = FinancialFactRepository(session).insert(
            financial_fact(entity_id=entity_id, value=value, provenance_overrides=provenance),
            actor="test:ingest",
        )
        session.commit()
        return result.fact


@pytest.mark.parametrize(
    ("statement", "message"),
    [
        ("UPDATE financial_facts SET value = 1 WHERE id = :id", "only allowed update"),
        # Smuggling another change in alongside a legitimate supersede is also refused.
        (
            "UPDATE financial_facts SET value = 1, superseded_at = now() WHERE id = :id",
            "only superseded_at may change",
        ),
        (
            "UPDATE financial_facts SET source_url = 'https://evil.example', "
            "superseded_at = now() WHERE id = :id",
            "only superseded_at may change",
        ),
        (
            "UPDATE financial_facts SET recorded_at = now() - interval '1 year', "
            "superseded_at = now() WHERE id = :id",
            "only superseded_at may change",
        ),
        ("UPDATE financial_facts SET superseded_at = NULL WHERE id = :id", "only allowed update"),
        ("DELETE FROM financial_facts WHERE id = :id", "DELETE is not allowed"),
        ("TRUNCATE financial_facts", "TRUNCATE is not allowed"),
    ],
)
def test_facts_cannot_be_changed(
    engine: Engine, entity_id: UUID, statement: str, message: str
) -> None:
    fact = store(engine, entity_id, "100")
    with engine.connect() as conn, pytest.raises(DBAPIError, match=message):
        conn.execute(text(statement), {"id": fact.id})


def test_system_time_comes_from_the_database(engine: Engine, entity_id: UUID) -> None:
    with Session(engine) as session:
        db_now = session.scalar(select(text("now()")))
        repo = FinancialFactRepository(session)
        fact = repo.insert(financial_fact(entity_id=entity_id), actor="test").fact
        assert fact.recorded_at == db_now
        assert fact.superseded_at is None
        session.rollback()


def test_source_restatement_respects_known_at(engine: Engine, entity_id: UUID) -> None:
    """Acceptance: a later source revision is a new version; an earlier known_at returns the
    old value (ADR-012)."""
    original = store(engine, entity_id, "100", published_at=FEB)
    restated = store(engine, entity_id, "90", published_at=AUG)

    assert restated.restated_flag is True
    assert restated.supersedes_fact_id == original.id
    assert restated.revision_reason == "restatement"
    assert (original.version, restated.version) == (1, 2)

    with Session(engine) as session:
        repo = FinancialFactRepository(session)

        def value_known_at(known_at: datetime) -> list[str]:
            return [str(f.value) for f in repo.as_of(known_at=known_at, entity_id=entity_id)]

        assert value_known_at(datetime(2025, 1, 15, tzinfo=UTC)) == []
        assert value_known_at(datetime(2025, 3, 1, tzinfo=UTC)) == ["100"]
        assert value_known_at(datetime(2025, 9, 1, tzinfo=UTC)) == ["90"]


def test_repeated_comparative_is_not_a_new_version(engine: Engine, entity_id: UUID) -> None:
    first = store(engine, entity_id, "100", published_at=FEB)
    again = store(engine, entity_id, "100.00", published_at=AUG)  # next 10-K repeats it
    assert again.id == first.id
    with Session(engine) as session:
        count = session.scalar(
            select(text("count(*)"))
            .select_from(FinancialFact)
            .where(FinancialFact.entity_id == entity_id)
        )
    assert count == 1


def test_out_of_order_publication_is_rejected(engine: Engine, entity_id: UUID) -> None:
    store(engine, entity_id, "100", published_at=AUG)
    with pytest.raises(FactConflictError):
        store(engine, entity_id, "95", published_at=FEB)


def test_own_correction_uses_system_time(engine: Engine, entity_id: UUID) -> None:
    wrong = store(engine, entity_id, "100", published_at=FEB)

    with Session(engine, expire_on_commit=False) as session:
        fixed = FinancialFactRepository(session).correct(
            wrong.id,
            financial_fact(
                entity_id=entity_id, value="110", provenance_overrides={"published_at": FEB}
            ),
            actor="test:correction",
        )
        session.commit()

    assert fixed.revision_reason == "correction"
    assert fixed.supersedes_fact_id == wrong.id
    late = datetime(2026, 1, 1, tzinfo=UTC)
    with Session(engine) as session:
        repo = FinancialFactRepository(session)
        superseded = session.get(FinancialFact, wrong.id)
        assert superseded is not None and superseded.superseded_at == fixed.recorded_at
        # Default: current belief, i.e. the corrected value, even for an early known_at.
        assert [str(f.value) for f in repo.as_of(known_at=late, entity_id=entity_id)] == ["110"]
        # What this database said before the correction.
        before = repo.as_of(known_at=late, system_time=wrong.recorded_at, entity_id=entity_id)
        assert [str(f.value) for f in before] == ["100"]

        audit = session.scalars(select(AuditLog).where(AuditLog.object_id == str(wrong.id))).all()
    assert [(a.action, a.actor) for a in audit] == [("supersede", "test:correction")]
    assert audit[0].details is not None and set(audit[0].details) == {"superseded_at"}
    assert audit[0].before_hash != audit[0].after_hash

    with engine.connect() as conn, pytest.raises(DBAPIError, match="already superseded"):
        conn.execute(
            text("UPDATE financial_facts SET superseded_at = now() WHERE id = :id"),
            {"id": wrong.id},
        )


def test_date_only_publication_is_not_visible_earlier_that_day(
    engine: Engine, entity_id: UUID
) -> None:
    release_day = date(2025, 3, 12)
    store(
        engine,
        entity_id,
        "100",
        published_at=end_of_day(release_day),
        published_at_precision="day",
    )
    with Session(engine) as session:
        repo = FinancialFactRepository(session)
        morning_new_york = datetime(2025, 3, 12, 13, 0, tzinfo=UTC)  # 09:00 EDT
        next_day = datetime(2025, 3, 13, 5, 0, tzinfo=UTC)
        assert repo.as_of(known_at=morning_new_york, entity_id=entity_id) == []
        assert len(repo.as_of(known_at=next_day, entity_id=entity_id)) == 1


