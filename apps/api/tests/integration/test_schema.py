APP_TABLES = {
    "signal_families",
    "strategies",
    "source_tiers",
    "sources",
    "entities",
    "instruments",
    "identifiers",
    "financial_facts",
    "audit_log",
}
FEB = datetime(2025, 2, 1, 21, 5, tzinfo=UTC)
AUG = datetime(2025, 8, 1, 20, 30, tzinfo=UTC)


def app_tables(url: URL) -> set[str]:
    engine = create_engine(url)
    try:
        with engine.connect() as conn:
            rows = conn.scalars(
                text("SELECT table_name FROM information_schema.tables WHERE table_schema='public'")
            )
            return set(rows) & APP_TABLES
    finally:
        engine.dispose()


# ---------- migrations ----------


def test_migration_upgrade_downgrade_upgrade(database_factory: Callable[[], URL]) -> None:
    url = database_factory()
    config = alembic_config(url)
    command.upgrade(config, "head")
    assert app_tables(url) == APP_TABLES
    command.downgrade(config, "base")
    assert app_tables(url) == set()
    command.upgrade(config, "head")
    assert app_tables(url) == APP_TABLES
    engine = create_engine(url)
    with engine.connect() as conn:
        extensions = set(conn.scalars(text("SELECT extname FROM pg_extension")))
    engine.dispose()
    assert {"timescaledb", "btree_gist"} <= extensions


def test_models_match_migrations(migrated_url: URL) -> None:
    # Raises AutogenerateDiffsDetected on drift between db/models.py and the migrations.
    command.check(alembic_config(migrated_url))


def test_guardrails_exist(engine: Engine) -> None:
    # `alembic check` does not compare triggers or exclusion constraints, so assert them here.
    with engine.connect() as conn:
        triggers = set(conn.scalars(text("SELECT tgname FROM pg_trigger WHERE NOT tgisinternal")))
        exclusions = set(
            conn.scalars(text("SELECT conname FROM pg_constraint WHERE contype = 'x'"))
        )
    assert {
        "signal_families_immutable",
        "strategies_immutable",
        "source_tiers_immutable",
        "financial_facts_system_time",
        "financial_facts_append_only",
        "financial_facts_no_truncate",
        "financial_facts_audit",
        "audit_log_append_only",
        "audit_log_no_truncate",
        "sources_audit",
        "identifiers_audit",
    } <= triggers
    assert exclusions == {"ex_identifiers_value_period", "ex_identifiers_subject_period"}


