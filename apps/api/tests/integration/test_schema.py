# ---------- identifiers ----------


def instrument(session: Session) -> Instrument:
    row = Instrument(instrument_type="equity", primary_exchange="XNYS", currency="USD")
    session.add(row)
    session.flush()
    return row


def ticker(subject: Instrument, value: str, start: datetime, **extra: object) -> Identifier:
    return Identifier(
        instrument_id=subject.id,
        id_type="ticker",
        id_namespace=str(extra.pop("namespace", "sec")),
        id_value=value,
        valid_from=start,
        source_id=TEST_SOURCE_ID,
        **extra,
    )


def test_identifier_periods_cannot_overlap(engine: Engine) -> None:
    symbol = f"T{uuid4().hex[:6].upper()}"
    y2020 = datetime(2020, 1, 1, tzinfo=UTC)
    y2024 = datetime(2024, 1, 1, tzinfo=UTC)
    with Session(engine) as session:
        old_owner, new_owner = instrument(session), instrument(session)
        first = ticker(old_owner, symbol, y2020)
        session.add(first)
        session.commit()

        session.add(ticker(new_owner, symbol, y2024))
        with pytest.raises(IntegrityError, match="ex_identifiers_value_period"):
            session.commit()
        session.rollback()

        # Ticker reassigned: close the old period, then the new one may start where it ends.
        first.valid_to = y2024
        session.add(ticker(new_owner, symbol, y2024))
        # Another provider's spelling of the same instrument lives in its own namespace.
        session.add(ticker(old_owner, symbol.replace("T", "T."), y2020, namespace="alpaca"))
        session.commit()

        session.add(ticker(old_owner, f"{symbol}X", y2024, valid_to=y2024))
        with pytest.raises(IntegrityError, match="valid_range"):
            session.commit()


# ---------- audit ----------


def test_mutable_rows_are_versioned_and_audited(engine: Engine) -> None:
    with Session(engine) as session:
        source = Source(
            id=f"src_{uuid4().hex[:8]}",
            name="Before",
            url="https://example.com",
            tier=2,
            license_status="unknown",
            update_cadence="daily",
            freshness_sla_seconds=3600,
        )
        session.add(source)
        session.commit()
        source.name = "After"
        session.commit()
        session.refresh(source)
        assert source.version == 2
        assert source.updated_at > source.created_at

        entries = session.scalars(
            select(AuditLog).where(AuditLog.object_id == source.id).order_by(AuditLog.id)
        ).all()
    assert [e.action for e in entries] == ["insert", "update"]
    changes = entries[1].details or {}
    assert changes["name"] == {"old": "Before", "new": "After"}
    assert entries[1].actor  # falls back to the database role when no actor is set


