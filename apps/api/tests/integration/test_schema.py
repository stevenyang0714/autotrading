def test_registries_match_spec(engine: Engine) -> None:
    with Session(engine) as session:
        families = session.scalars(select(SignalFamilyRow).order_by(SignalFamilyRow.id)).all()
        strategies = session.scalars(select(StrategyRow)).all()
        tiers = session.scalars(select(SourceTierRow).order_by(SourceTierRow.tier)).all()
    assert [(f.id, f.name) for f in families] == [(f.id, f.name) for f in SIGNAL_FAMILIES]
    assert sorted((s.id, s.name, s.default_mode, s.unlock_condition) for s in strategies) == sorted(
        (s.id, s.name, s.default_mode, s.unlock_condition) for s in STRATEGIES
    )
    assert [(t.tier, t.label, t.role, t.examples) for t in tiers] == [
        (t.tier, t.label, t.role, t.examples) for t in SOURCE_TIERS
    ]


